    "ClientId"      text                        NOT NULL,
    "ApiKeyId"      integer                     NOT NULL,
    "IsPublic"      boolean                     NOT NULL DEFAULT FALSE,
    "CreatedAt"     timestamp with time zone    NOT NULL DEFAULT NOW(),
