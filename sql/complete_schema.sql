-- ============================================================
-- 2. ApiKeys — API 密钥表
-- ============================================================
CREATE TABLE "ApiKeys" (
    "Id"            integer                     NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "Key"           text                        NOT NULL,
    "Description"   text                        NOT NULL DEFAULT '',
    "CreatedAt"     timestamp with time zone    NOT NULL,
    "ExpiresAt"     timestamp with time zone    NOT NULL,
    "IsDeleted"     boolean                     NOT NULL DEFAULT FALSE,
    "KeyType"       text                        NOT NULL DEFAULT 'Admin',
    CONSTRAINT "PK_ApiKeys" PRIMARY KEY ("Id")
);

COMMENT ON TABLE "ApiKeys" IS 'API密钥表：Admin 和 Temporary 两种类型';
COMMENT ON COLUMN "ApiKeys"."KeyType" IS 'Admin=管理密钥, Temporary=临时密钥';

-- ============================================================
-- 3. IpWhitelists — IP 白名单表
-- ============================================================
CREATE TABLE "IpWhitelists" (
    "Id"            integer                     NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "IpAddress"     text                        NOT NULL,
    "Description"   text                        NOT NULL DEFAULT '',
    "CreatedAt"     timestamp with time zone    NOT NULL,
    "IsEnabled"     boolean                     NOT NULL DEFAULT TRUE,
    CONSTRAINT "PK_IpWhitelists" PRIMARY KEY ("Id")
);

COMMENT ON TABLE "IpWhitelists" IS 'IP白名单：用于限制公网临时密钥申请';

-- ============================================================
-- 4. Files — 文件记录表
-- ============================================================
CREATE TABLE "Files" (
    -- 基础字段（InitialCreate）
    "Id"                integer                     NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    "FileName"          text                        NOT NULL,
    "StoredFileName"    text                        NOT NULL,
    "FileSize"          bigint                      NOT NULL,
    "ContentType"       text                        NOT NULL,
    "UploadedAt"        timestamp with time zone    NOT NULL DEFAULT NOW(),

    -- 外键关联
    "ApiKeyId"          integer                     NULL,

    -- 加密字段（Phase 1.5）
    "EncryptionVersion" smallint                    NOT NULL DEFAULT 0,
    "KeyVersion"        smallint                    NOT NULL DEFAULT 0,
    "DiskFileName"      text                        NOT NULL DEFAULT '',
    "FileHash"          text                        NULL,
    "BlockSize"         integer                     NOT NULL DEFAULT 1048576,

    -- 公共访问字段（Phase 2）
    "IsPublic"          boolean                     NOT NULL DEFAULT FALSE,
    "PublicPath"        text                        NULL,

    -- WS 存储字段（Phase 3）
    "StorageMode"       text                        NOT NULL DEFAULT 'Local',
    "ClientId"          text                        NULL,
    "StoragePath"       text                        NULL,

    CONSTRAINT "PK_Files" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Files_ApiKeys_ApiKeyId"
        FOREIGN KEY ("ApiKeyId") REFERENCES "ApiKeys" ("Id")
        ON DELETE SET NULL
);

-- Files 索引
CREATE INDEX "IX_Files_ApiKeyId"       ON "Files" ("ApiKeyId");
CREATE INDEX "IX_Files_DiskFileName"   ON "Files" ("DiskFileName");
CREATE INDEX "IX_Files_IsPublic"       ON "Files" ("IsPublic");

COMMENT ON TABLE "Files" IS '文件记录表：支持加密、公共访问、WS分布式存储';
COMMENT ON COLUMN "Files"."EncryptionVersion" IS '0=未加密, 1=AES-256-GCM分块';
COMMENT ON COLUMN "Files"."KeyVersion"        IS '加密密钥版本号';
COMMENT ON COLUMN "Files"."DiskFileName"      IS '磁盘上的加密/随机文件名（含子目录前缀）';
COMMENT ON COLUMN "Files"."StorageMode"       IS 'Local=本地, WebSocket=远程, Hybrid=混合';

-- ============================================================
-- 5. WsClients — WS 客户端注册表
-- ============================================================
CREATE TABLE "WsClients" (
    "Id"                text                        NOT NULL,
    "ClientSecretHash"  text                        NOT NULL,
    "Description"       text                        NOT NULL DEFAULT '',
    "IsEnabled"         boolean                     NOT NULL DEFAULT TRUE,
    "PathPrefixes"      text                        NOT NULL DEFAULT '',
    "StorageCapacity"   bigint                      NOT NULL DEFAULT -1,
    "CurrentStorage"    bigint                      NOT NULL DEFAULT 0,
    "LastConnectedAt"   timestamp with time zone    NULL,
    "CreatedAt"         timestamp with time zone    NOT NULL DEFAULT NOW(),
    CONSTRAINT "PK_WsClients" PRIMARY KEY ("Id")
);

COMMENT ON TABLE "WsClients" IS 'WebSocket客户端注册表：存储节点管理';
COMMENT ON COLUMN "WsClients"."Id"               IS '客户端唯一标识';
COMMENT ON COLUMN "WsClients"."ClientSecretHash" IS 'SHA256(clientSecret)';
COMMENT ON COLUMN "WsClients"."PathPrefixes"     IS '逗号分隔的路径前缀，如 /public/*,/shared/*';
COMMENT ON COLUMN "WsClients"."StorageCapacity"  IS '-1=无限制';

